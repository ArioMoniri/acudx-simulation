def intent_cluster(intent: str) -> Optional[str]:
    for name, intents in HISTORY_CLUSTERS.items():
        if intent in intents:
            return name
    return None


def maneuver_system(maneuver: str) -> Optional[str]:
    for name, mans in EXAM_SYSTEMS.items():
        if maneuver in mans:
            return name
    return None


def layer_kind(layer: str) -> str:
    return layer.split(".", 1)[0]


def valid_layer(layer: str) -> bool:
    kind, _, sub = layer.partition(".")
    if kind == "history":
        return sub in HISTORY_CLUSTERS
    if kind == "exam":
        return sub in EXAM_SYSTEMS
    if kind == "event":
        return bool(re.fullmatch(r"[a-z0-9_\-]{1,64}", sub))
    return kind in ("treatments", "results", "debrief") and not sub


