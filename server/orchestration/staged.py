def _sample(req: dict[str, Any], memory: Optional[LearnerMemory]) -> tuple[dict[str, Any], Optional[str]]:
    rng = random.Random(req["seed"])
    blueprint = req.get("blueprint") or {}
    if blueprint.get("condition_id"):
        hit = next((c for c in CATALOG if c["id"] == blueprint["condition_id"]), None)
        if hit is not None:
            return json.loads(json.dumps(hit)), None
    exclude: set[str] = set()
    steer: Optional[str] = None
    if req.get("learner_id") and memory is not None:
        exclude = set(memory.conditions_seen(req["learner_id"]))
        weak = memory.weak_systems(req["learner_id"])
        if weak and not req.get("system") and rng.random() < WEAK_SYSTEM_STEER_P:
            steer = weak[0]
    cond = sample_condition(system=req.get("system") or steer, difficulty=req.get("difficulty"),
                            complaint=req.get("complaint"), rng=rng, exclude_ids=exclude or None)
    return cond, steer


class StagedRuntime:
    """Runs S1 and the layers for each thread and keeps the SSE log in the store."""

    def __init__(self, llm: Optional[StructuredLLM], store: CaseStore, memory: Optional[LearnerMemory] = None,
                 *, continuation: bool = True, s1_attempts: int = 2, layer_attempts: int = 2) -> None:
        self.llm = llm
        self.store = store
        self.memory = memory
        self.continuation = continuation
        self.s1_attempts = max(1, s1_attempts)
        self.layer_attempts = max(1, layer_attempts)
        self._tasks: dict[str, asyncio.Task[Any]] = {}
        self._layer_tasks: dict[tuple[str, str], asyncio.Task[Any]] = {}
        self._render_tasks: dict[tuple[str, str, str], asyncio.Task[Any]] = {}
        self._notify: dict[str, asyncio.Event] = {}
        self._spawned: set[asyncio.Task[Any]] = set()
        self._limiter = _Limiter()                       # one global limit (GPU worker, explicit env)
        self._thread_limiters: dict[str, _Limiter] = {}  # per-thread limits (Claude route)
        # Queued background layers a learner is now waiting for: they skip the queue.
        self._urgent: set[tuple[str, str]] = set()
        # Set once the thread's kernel stage is over (written or failed): a history or exam layer the learner
        # asks for before then waits for it, so it is written against the kernel like the continuation's.
        self._kernel_done: dict[str, asyncio.Event] = {}
        self._medians: dict[str, deque[float]] = {k: deque(maxlen=50) for k in DEFAULT_ETA_MS}

    # ------------------------------------------------------------- events
    def emit(self, thread_id: str, event: str, data: dict[str, Any]) -> int:
        eid = self.store.append_event(thread_id, event, data)
        ev = self._notify.get(thread_id)
        if ev is not None:
            ev.set()
        return eid

    def eta_ms(self) -> dict[str, int]:
        return {k: int(statistics.median(v)) if v else DEFAULT_ETA_MS[k] for k, v in self._medians.items()}

    async def tail(self, thread_id: str, after: int = 0, *, cap_s: float = 900.0,
                   until: tuple[str, ...] = ("done",), follow: bool = False
                   ) -> AsyncIterator[tuple[int, str, dict[str, Any]]]:
        """Replay events after ``after`` and follow the log until an ``until`` event or the cap.
        A fatal error (S1 failed) also ends the tail. With ``follow`` the tail stays open after
        ``done`` until the cap (room members receive later branch events, renderings and Director
        updates) and yields ``(cursor, "", {})`` as a keepalive while the log is idle."""
        loop = asyncio.get_running_loop()
        deadline = loop.time() + cap_s
        cursor = int(after or 0)
        while True:
            ev = self._notify.setdefault(thread_id, asyncio.Event())
            ev.clear()
            rows = self.store.events(thread_id, cursor)
            for eid, name, data in rows:
                cursor = eid
                yield eid, name, data
                if not follow and (name in until or (name == "error" and data.get("fatal"))):
                    return
            if rows:
                continue        # read again before waiting: the log may already hold more
            if not follow and not self.running(thread_id):
                return
            remaining = deadline - loop.time()
            if remaining <= 0:
                return
            try:
                await asyncio.wait_for(ev.wait(), min(remaining, 15.0))
            except asyncio.TimeoutError:
                if follow and deadline - loop.time() > 0:
                    yield cursor, "", {}
                continue

    def spawn(self, coro: Any) -> asyncio.Task[Any]:
        """Run same-thread background work (a branch event layer); failures land on the thread log."""
        async def quiet() -> None:
            try:
                await coro
            except Exception:  # noqa: BLE001 - reported through the thread's error event
                pass
        task = asyncio.create_task(quiet())
        self._spawned.add(task)
        task.add_done_callback(self._spawned.discard)
        return task

    def running(self, thread_id: str) -> bool:
        t = self._tasks.get(thread_id)
        if t is not None and not t.done():
            return True
        return any(not lt.done() for (tid, _l), lt in self._layer_tasks.items() if tid == thread_id)

    async def wait(self, thread_id: str) -> None:
        """Wait for the thread's background work (tests and the blocking generate route)."""
        while True:
            pending = [t for t in [self._tasks.get(thread_id)] if t is not None and not t.done()]
            pending += [t for (tid, _l), t in self._layer_tasks.items() if tid == thread_id and not t.done()]
            if not pending:
                return
            await asyncio.gather(*pending, return_exceptions=True)

    # ---------------------------------------------------------- start
    def start(self, request: dict[str, Any], thread_id: Optional[str] = None) -> str:
        """Create the thread for one learner request and launch S1 (+ continuation)."""
        thread_id = thread_id or str(uuid.uuid4())
        req = normalize_request(request)
        bp = request.get("blueprint") if isinstance(request.get("blueprint"), dict) else None
        if bp:
            req["blueprint"] = {"condition_id": bp.get("condition_id"), "difficulty": bp.get("difficulty"),
                                "objectives": [str(o)[:200] for o in (bp.get("objectives") or [])][:5]}
            if req.get("difficulty") is None and bp.get("difficulty"):
                req["difficulty"] = max(1, min(5, int(bp["difficulty"])))
        cond, steer = _sample(req, self.memory)
        if req.get("complaint"):
            cond["requested_complaint"] = req["complaint"]
        acuity = int(cond["typical_acuity"])
        difficulty = req["difficulty"] if req.get("difficulty") is not None else int(cond["difficulty"])
        state: dict[str, Any] = {
            "thread_id": thread_id, "owner": req.get("learner_id"), "requester": request.get("requester"),
            "source": "model", "request": req,
            "seed": req["seed"], "locale": req["locale"], "condition": cond, "acuity": acuity,
            "difficulty": difficulty, "steered_system": steer, "kernel": None, "opening": None, "layers": {},
            "layer_order": [], "spec": None, "director": None, "status": "opening", "models": [], "trace": [],
            "normalization": [], "corrections": [], "t0": time.time(), "timings": {},
        }
        self.store.put(thread_id, state)
        self.emit(thread_id, "start", {"thread_id": thread_id, "stages": ["s1", "history", "exam", "treatments",
                                                                         "results"], "eta_ms": self.eta_ms()})
        self._tasks[thread_id] = asyncio.create_task(self._run(thread_id))
        return thread_id

    def kernel_event(self, thread_id: str) -> asyncio.Event:
        return self._kernel_done.setdefault(thread_id, asyncio.Event())

    async def _run(self, thread_id: str) -> None:
        try:
            ok = await self._s1(thread_id)
            if ok:
                await self._kernel(thread_id)
        finally:
            self.kernel_event(thread_id).set()
        if ok and self.continuation:
            try:
                await asyncio.wait_for(self._continue(thread_id), CONTINUATION_CAP_S)
            except asyncio.TimeoutError:
                self.emit(thread_id, "error", {"stage": "continuation", "error": "continuation_timeout",
                                               "status": 504, "retryable": True, "thread_id": thread_id})
            await self._judge_async(thread_id)
            self._thread_limiters.pop(thread_id, None)
            st = self.store.update(thread_id, lambda s: s.update(status=("complete" if s["status"] != "failed"
                                                                       else "failed")))
            if st is not None:
                self.emit(thread_id, "done", {"thread_id": thread_id, "spec": st.get("spec"),
                                              "timings": st.get("timings")})

    # ---------------------------------------------------------- model call
    async def _call(self, thread_id: str, node: str, messages: list[dict[str, str]], schema: dict[str, Any],
                    *, max_tokens: int, temperature: float, on_text: Optional[Callable[[str], Any]] = None
                    ) -> LLMReply:
        if self.llm is None:
            raise ModelUnreachable("no model endpoint configured")
        started = time.monotonic()
        reply = await self.llm.complete_json(messages, schema=schema, schema_name=node.replace(".", "_"),
                                             role="casegen", temperature=temperature, max_tokens=max_tokens,
                                             on_text=on_text, node=node)
        event = make_event(node, started=started, model=reply.model, model_requested=reply.model_requested,
                           provider=reply.provider, tokens_in=reply.tokens_in, tokens_out=reply.tokens_out,
                           cost_usd=reply.extras.get("cost_usd"), cost_basis=reply.extras.get("cost_basis"),
                           finish_reason=reply.extras.get("finish_reason"), max_tokens=max_tokens)

        def rec(s: dict[str, Any]) -> None:
            s["trace"] = (list(s.get("trace") or []) + [event])[-80:]
            s["models"] = sorted(set(s.get("models") or []) | {reply.model})
            s["model"] = s["models"][0] if len(s["models"]) == 1 else s["models"]

        self.store.update(thread_id, rec)
        return reply

    # ---------------------------------------------------------- S1
    async def _s1(self, thread_id: str) -> bool:
        state = self.store.get(thread_id)
        assert state is not None
        cond = state["condition"]
        req = state["request"]
        t0 = time.monotonic()
        first_text: dict[str, Optional[float]] = {"t": None}
        tracker = DeltaTracker(root="opening")

        def on_text(text: str) -> None:
            for path, value in tracker.feed(text):
                if first_text["t"] is None and isinstance(value, str) and value.strip():
                    first_text["t"] = (time.monotonic() - t0) * 1000.0
                self.emit(thread_id, "opening.delta", {"path": path, "value": value})

        messages = s1_messages(cond, locale=state["locale"], acuity=state["acuity"],
                               difficulty=state["difficulty"], candidates=candidate_ids(cond),
                               complaint=req.get("complaint"), blueprint=req.get("blueprint"))
        issues: list[str] = []
        draft: Optional[dict[str, Any]] = None
        notes: list[str] = []
        for attempt in range(self.s1_attempts):
            msgs = messages if not issues else [messages[0], {"role": "user", "content": messages[1]["content"]
                                                              + "\nFIX: " + "; ".join(issues)}]
            try:
                reply = await self._call(thread_id, "s1", msgs, S1_SCHEMA, max_tokens=S1_MAX_TOKENS,
                                         temperature=TEMPERATURE["s1"], on_text=on_text if attempt == 0 else None)
                draft, notes = gate_s1(dict(reply.data), cond, acuity=state["acuity"], complaint=req.get("complaint"))
                break
            except LayerRejected as exc:
                issues = exc.issues
                draft = None
            except ModelOutputInvalid as exc:
                issues = [f"the reply was not valid JSON: {str(exc)[:80]}"]
                draft = None
            except ModelUnreachable as exc:
                self._fail(thread_id, "s1", "model_unreachable", 503, str(exc))
                return False
        if draft is None:
            self._fail(thread_id, "s1", "model_output_invalid", 502, "; ".join(issues)[:300])
            return False
        t_open = (time.monotonic() - t0) * 1000.0
        self._medians["s1"].append(t_open)
        def apply(s: dict[str, Any]) -> None:
            s["opening"] = draft["opening"]
            s["normalization"] = list(s.get("normalization") or []) + notes
            s["status"] = "playable"
            s["timings"] = {**(s.get("timings") or {}), "t_first_text_ms": round(first_text["t"] or t_open, 1),
                            "t_opening_ms": round(t_open, 1)}
            s["spec"] = assemble_spec(s)

        st = self.store.update(thread_id, apply)
        assert st is not None
        validate_spec(st["spec"])
        if req.get("learner_id") and self.memory is not None:
            self.memory.record_case(req["learner_id"], cond["id"], cond["system"])
        self.emit(thread_id, "opening.ready", {"thread_id": thread_id, "opening": st["opening"], "spec": st["spec"],
                                               "layers": {}, "timings": st["timings"]})
        return True

    async def _kernel(self, thread_id: str) -> None:
        """The hidden kernel, right after the opening. A failure is not fatal: the layers are then
        written from the opening alone, and the error is on the thread log."""
        state = self.store.get(thread_id) or {}
        cond = state["condition"]
        started = time.monotonic()
        messages = kernel_messages(cond, state.get("opening") or {}, locale=state["locale"], acuity=state["acuity"],
                                   candidates=candidate_ids(cond))
        kernel: Optional[dict[str, Any]] = None
        notes: list[str] = []
        issues: list[str] = []
        for _attempt in range(self.layer_attempts):
            msgs = messages if not issues else [messages[0], {"role": "user", "content": messages[1]["content"]
                                                              + "\nFIX: " + "; ".join(issues)}]
            try:
                reply = await self._call(thread_id, "kernel", msgs, KERNEL_SCHEMA, max_tokens=MAX_TOKENS["kernel"],
                                         temperature=TEMPERATURE["layer"])
                kernel, notes = gate_kernel(dict(reply.data), cond)
                break
            except LayerRejected as exc:
                issues = exc.issues
            except ModelOutputInvalid:
                issues = ["the reply was not valid JSON"]
            except ModelUnreachable as exc:
                issues = [str(exc)[:120]]
                break
        if kernel is None:
            self.emit(thread_id, "error", {"stage": "kernel", "error": "kernel_failed", "status": 502,
                                           "retryable": True, "detail": "; ".join(issues)[:300],
                                           "thread_id": thread_id})
            return
        anchors, _dropped = resolve_anchors(list(kernel.get("anchor_ids") or []), cond)
        final = kernel

        def apply(s: dict[str, Any]) -> None:
            s["kernel"] = final
            s["anchors"] = [{"statement_id": a["statement_id"], "statement_en": a["statement_en"],
                             "statement_tr": a["statement_tr"], "source": a["source"], "citation": a["citation"],
                             "codes": a.get("codes", [])} for a in anchors]
            s["normalization"] = (list(s.get("normalization") or []) + notes)[-60:]
            s["timings"] = {**(s.get("timings") or {}),
                            "t_kernel_ms": round((time.time() - float(s.get("t0") or time.time())) * 1000.0, 1)}
            s["spec"] = assemble_spec(s)

        st = self.store.update(thread_id, apply)
        if st is not None:
            validate_spec(st["spec"])
        self.emit(thread_id, "kernel", {"status": "ready", "latency_ms": round((time.monotonic() - started) * 1000, 1)})

    def _fail(self, thread_id: str, stage: str, code: str, status: int, detail: str) -> None:
        self.store.update(thread_id, lambda s: s.update(status="failed", error={"stage": stage, "error": code}))
        self.emit(thread_id, "error", {"stage": stage, "error": code, "status": status, "retryable": True,
                                       "fatal": stage == "s1", "detail": detail[:300], "thread_id": thread_id})

    # ---------------------------------------------------------- continuation
    def _claude_route(self) -> bool:
        """The case generator's calls go to Claude (the Claude route, or an Anthropic registry row)."""
        llm = self.llm
        if llm is None:
            return False
        try:
            if llm.claude_active():
                return True
            from server.orchestration.llm import anthropic_row_endpoint
            return anthropic_row_endpoint(llm.endpoint("casegen"))
        except Exception:  # noqa: BLE001 - an unreadable route keeps the safe default
            return False

    def layer_concurrency(self) -> int:
        """Background layer calls in flight: CASEGEN_LAYER_CONCURRENCY when set, else 3 on the
        Claude route, else 1 (the GPU worker does not batch, doc 15 12.6)."""
        explicit = os.environ.get("CASEGEN_LAYER_CONCURRENCY")
        if explicit:
            try:
                return max(1, int(explicit))
            except ValueError:
                return LAYER_CONCURRENCY
        return CLAUDE_LAYER_CONCURRENCY if self._claude_route() else LAYER_CONCURRENCY

    def limiter_for(self, thread_id: str) -> _Limiter:
        """The limit a background layer of ``thread_id`` queues on: per thread on the Claude
        route (calls are served independently, so learners must not queue behind each other),
        else the runtime-wide one (the GPU worker's decode budget is shared; an explicit
        CASEGEN_LAYER_CONCURRENCY is also one global limit)."""
        if not os.environ.get("CASEGEN_LAYER_CONCURRENCY") and self._claude_route():
            return self._thread_limiters.setdefault(thread_id, _Limiter())
        return self._limiter

    def core_layers(self, state: dict[str, Any]) -> list[str]:
        systems = [f"exam.{s}" for s in ((state.get("kernel") or {}).get("exam_systems") or [])]
        out = list(CORE_LAYERS_FIXED[:4]) + systems + list(CORE_LAYERS_FIXED[4:])
        return list(dict.fromkeys(out))

    async def _continue(self, thread_id: str) -> None:
        state = self.store.get(thread_id)
        if state is None:
            return
        names = self.core_layers(state)
        for name in names:
            self._mark_pending(thread_id, name, "continuation")
        # Dependency order (continuation_waves); inside a wave the limiter decides how many run
        # at once (1 on the GPU worker, 3 on Claude), so the order on one call at a time is the
        # same as before: presenting, the other history and exam layers, treatments, results.
        at_once = self._claude_route() and not os.environ.get("CASEGEN_LAYER_CONCURRENCY")
        for wave in continuation_waves(names, history_at_once=at_once):
            await asyncio.gather(*(self.ensure_layer(thread_id, n, reason="continuation") for n in wave),
                                 return_exceptions=True)
        # One more background attempt for a history layer that failed its gate or its JSON: otherwise the first
        # question that needs it waits for a fresh write (two attempts, 20 s or more on Claude). Safety vetoes
        # and unreachable models are not retried here.
        st = self.store.get(thread_id) or {}
        failed = [n for n in names if layer_kind(n) == "history"
                  and ((st.get("layers") or {}).get(n) or {}).get("status") == "failed"
                  and ((st.get("layers") or {}).get(n) or {}).get("error") in ("layer_rejected", "model_output_invalid")]
        if failed:
            await asyncio.gather(*(self.ensure_layer(thread_id, n, reason="continuation") for n in failed),
                                 return_exceptions=True)

    def _mark_pending(self, thread_id: str, layer: str, reason: str) -> bool:
        changed = {"v": False}

        def m(s: dict[str, Any]) -> None:
            entry = (s.setdefault("layers", {})).get(layer)
            if entry and entry.get("status") in ("ready", "pending"):
                return
            s["layers"][layer] = {"status": "pending", "reason": reason, "attempts": 0, "seen": False}
            if layer not in s.setdefault("layer_order", []):
                s["layer_order"].append(layer)
            changed["v"] = True

        self.store.update(thread_id, m)
        if changed["v"]:
            self.emit(thread_id, "layer.pending", {"layer": layer, "reason": reason})
        return changed["v"]

    async def ensure_layer(self, thread_id: str, layer: str, *, reason: str = "access",
                           extra: str = "", at_ms: Optional[int] = None) -> dict[str, Any]:
        """The layer's entry, generating it once (first access or continuation); concurrent callers
        share one in-flight call."""
        if not valid_layer(layer):
            raise KeyError(layer)
        state = self.store.get(thread_id)
        if state is None:
            raise KeyError(thread_id)
        entry = (state.get("layers") or {}).get(layer)
        if entry and entry.get("status") == "ready":
            return entry
        key = (thread_id, layer)
        if (layer_kind(layer) in ("history", "exam") and state.get("kernel") is None and self.running(thread_id)
                and not self.kernel_event(thread_id).is_set()):
            try:
                await asyncio.wait_for(asyncio.shield(self.kernel_event(thread_id).wait()), KERNEL_WAIT_S)
            except asyncio.TimeoutError:
                pass
            state = self.store.get(thread_id) or state
            entry = (state.get("layers") or {}).get(layer)
            if entry and entry.get("status") == "ready":
                return entry
        task = self._layer_tasks.get(key)
        if task is None or task.done():
            self._mark_pending(thread_id, layer, reason)
            task = asyncio.create_task(self._generate_layer(thread_id, layer, extra=extra, at_ms=at_ms,
                                                            background=(reason == "continuation")))
            self._layer_tasks[key] = task
        elif reason != "continuation" and key not in self._urgent:
            # The learner now waits for a layer the continuation has queued: let it go ahead
            # of the queue instead of waiting for the layers in front of it.
            self._urgent.add(key)
            await self._limiter.wake()
            lim = self._thread_limiters.get(thread_id)
            if lim is not None:
                await lim.wake()
        await asyncio.shield(task)
        state = self.store.get(thread_id) or {}
        return (state.get("layers") or {}).get(layer) or {}

    async def _generate_layer(self, thread_id: str, layer: str, *, extra: str = "",
                              issues: Optional[list[str]] = None, at_ms: Optional[int] = None,
                              background: bool = True) -> None:
        """Write one layer. Background continuation queues on the concurrency limit; a layer the
        learner is waiting for (first access, a branch event) goes straight to the model."""
        kind = layer_kind(layer)
        started = time.monotonic()
        issues = list(issues or [])
        data: Optional[dict[str, Any]] = None
        notes: list[str] = []
        error: Optional[tuple[str, int, str]] = None
        key = (thread_id, layer)
        slot = (self.limiter_for(thread_id).slot(self.layer_concurrency, lambda: key in self._urgent)
                if background else contextlib.nullcontext())
        try:
            async with slot:
                self._urgent.discard(key)
                for _attempt in range(self.layer_attempts):
                    state = self.store.get(thread_id) or {}
                    schema, cap = layer_schema(layer)
                    try:
                        msgs = layer_messages(state, layer, extra=extra, issues=issues)
                        reply = await self._call(thread_id, f"layer:{layer}", msgs, schema, max_tokens=cap,
                                                 temperature=TEMPERATURE["layer"])
                        data, notes = gate_layer(layer, dict(reply.data), state)
                        if kind == "treatments":
                            await self._safety_gate_treatments(thread_id, data, state)
                        elif kind == "event":
                            data = await self._safety_gate_event(thread_id, layer, data, state)
                        error = None
                        break
                    except SafetyVeto as exc:
                        issues = exc.issues
                        data = None
                        error = ("safety_veto", 502, "; ".join(exc.issues))
                    except LayerRejected as exc:
                        issues = exc.issues
                        data = None
                        error = ("layer_rejected", 502, "; ".join(exc.issues))
                    except ModelOutputInvalid as exc:
                        issues = ["the reply was not valid JSON"]
                        data = None
                        error = ("model_output_invalid", 502, str(exc))
                    except ModelUnreachable as exc:
                        data = None
                        error = ("model_unreachable", 503, str(exc))
                        break
        finally:
            self._urgent.discard(key)
        latency = (time.monotonic() - started) * 1000.0
        if kind in self._medians and data is not None:
            self._medians[kind].append(latency)
        if data is None:
            err = error or ("layer_failed", 502, "")
            reason = failure_reason(layer, err[0], self.layer_attempts)
            failed_issues = [str(i)[:200] for i in issues][:6]

            def failed(s: dict[str, Any]) -> None:
                s.setdefault("layers", {})[layer] = {**(s["layers"].get(layer) or {}), "status": "failed",
                                                     "error": err[0], "reason": reason, "issues": failed_issues}
            self.store.update(thread_id, failed)
            self.emit(thread_id, "error", {"stage": layer, "error": err[0], "status": err[1], "retryable": True,
                                           "reason": reason, "issues": failed_issues,
                                           "detail": err[2][:300], "thread_id": thread_id})
            return
        final = data

        def ready(s: dict[str, Any]) -> None:
            prev = s.setdefault("layers", {}).get(layer) or {}
            prev.pop("error", None)
            s["layers"][layer] = {"status": "ready", "data": final, "attempts": int(prev.get("attempts") or 0) + 1,
                                  "seen": bool(prev.get("seen")), "latency_ms": round(latency, 1),
                                  **({"at_ms": at_ms} if at_ms is not None else {})}
            if layer not in s.setdefault("layer_order", []):
                s["layer_order"].append(layer)
            s["normalization"] = (list(s.get("normalization") or []) + notes)[-60:]
            s["spec"] = assemble_spec(s)
            refresh_director(s)

        st = self.store.update(thread_id, ready)
        if st is None:
            return
        validate_spec(st["spec"])
        self.emit(thread_id, "layer.ready", {"layer": layer, "data": final, "spec": st["spec"]})

    # ---------------------------------------------------------- renderings (on demand)
    async def render_layer(self, thread_id: str, layer: str, locale: str) -> dict[str, Any]:
        """A rendering of a layer the learner has seen, in ``locale``: one model call per layer,
        cached on the thread (``state["renderings"][locale][layer]``) and reused until the source
        layer changes. The source text stays authoritative: the Director, the judges and grading
        read it, and the rendering fills only the other locale's slot of the spec (TR for an EN
        case, EN for a TR case). Raises KeyError (no
        thread or unknown layer), ValueError (the case's own locale, or a locale without
        renderings) and LookupError (the layer is not written yet)."""
        if not renderable(layer):
            raise KeyError(layer)
        state = self.store.get(thread_id)
        if state is None:
            raise KeyError(thread_id)
        if locale not in RENDER_LOCALES or locale == state.get("locale"):
            raise ValueError(locale)
        src = render_source(state, layer)
        if src is None:
            raise LookupError(layer)
        cached = ((state.get("renderings") or {}).get(locale) or {}).get(layer) or {}
        if cached.get("status") == "ready" and cached.get("source") == render_fingerprint(layer, src):
            return cached
        key = (thread_id, locale, layer)
        task = self._render_tasks.get(key)
        if task is None or task.done():
            task = asyncio.create_task(self._render(thread_id, layer, locale))
            self._render_tasks[key] = task
        await asyncio.shield(task)
        st = self.store.get(thread_id) or {}
        return ((st.get("renderings") or {}).get(locale) or {}).get(layer) or {}

    async def _render(self, thread_id: str, layer: str, locale: str) -> None:
        state = self.store.get(thread_id) or {}
        src = render_source(state, layer) or {}
        paths = render_paths(layer, src)
        sources = [t for _p, t in paths]
        fingerprint = render_fingerprint(layer, src)
        issues: list[str] = []
        texts: Optional[list[str]] = None
        error = "rendering_rejected"
        if sources:
            cap = min(MAX_TOKENS["render"], 80 + sum(len(t) for t in sources))
            for _attempt in range(self.layer_attempts):
                msgs = render_messages(layer, sources, locale)
                if issues:
                    msgs[1]["content"] += "\nFIX: " + "; ".join(issues[:6])
                try:
                    reply = await self._call(thread_id, f"render:{layer}", msgs, render_schema(len(sources)),
                                             max_tokens=cap, temperature=TEMPERATURE["patch"])
                    texts = gate_rendering(sources, list(reply.data.get("texts") or []))
                    break
                except LayerRejected as exc:
                    issues = exc.issues
                except ModelOutputInvalid:
                    issues = ["the reply was not valid JSON"]
                    error = "model_output_invalid"
                except ModelUnreachable:
                    error = "model_unreachable"
                    break
        else:
            texts = []
        if texts is None:
            entry: dict[str, Any] = {"status": "failed", "error": error, "issues": issues[:6], "source": fingerprint}
        else:
            entry = {"status": "ready", "data": apply_rendering(layer, src, texts), "source": fingerprint}
        final = entry

        def put(s: dict[str, Any]) -> None:
            s.setdefault("renderings", {}).setdefault(locale, {})[layer] = final
            if s.get("opening"):
                s["spec"] = assemble_spec(s)

        st = self.store.update(thread_id, put)
        if st is None:
            return
        if final["status"] == "ready":
            validate_spec(st["spec"])
            self.emit(thread_id, "layer.rendered", {"layer": layer, "locale": locale, "data": final["data"],
                                                    "spec": st["spec"]})
        else:
            self.emit(thread_id, "error", {"stage": f"render:{layer}", "error": final["error"], "status": 502,
                                           "retryable": True, "locale": locale, "issues": final["issues"],
                                           "reason": f"The {_LOCALE_NAME.get(locale, locale)} rendering of this "
                                                     "part could not be written; the source text is shown.",
                                           "thread_id": thread_id})

    # ---------------------------------------------------------- safety (blocking)
    async def _safety_gate_treatments(self, thread_id: str, data: dict[str, Any], state: dict[str, Any]) -> None:
        """The safety judge blocks the treatment layer: the deterministic checks first, then the
        model judge on the case with this table. A veto raises :class:`SafetyVeto`; the layer is
        rewritten once with the issues and otherwise fails honestly (06b F30). The fixture is a
        validation oracle only: its appropriateness is never written into the table."""
        draft = {**(source_spec(state) if state.get("opening") else {}), "treatments": [
            {**t, "label_tr": t.get("label_en")} for t in data["treatments"]]}
        vote, event = await J.run_judge("safety_dosing", draft, state["condition"], self.llm, round_no=0)
        self.store.update(thread_id, lambda s: s.update(trace=(list(s.get("trace") or []) + [event])[-80:]))
        self.emit(thread_id, "judge", {"layer": "treatments", "judge": "safety_dosing", "blocking": True,
                                       "decision": "accept" if vote["verdict"] == "pass" else "rejected",
                                       "issues": vote.get("issues") or []})
        if vote["verdict"] != "pass":
            raise SafetyVeto(list(vote.get("issues") or ["safety judge vetoed the table"]))

    async def _safety_gate_event(self, thread_id: str, layer: str, data: dict[str, Any], state: dict[str, Any]
                                 ) -> dict[str, Any]:
        text = " ".join([*data.get("facts", []), data.get("nurse_call", ""),
                         *[c.get("finding", "") for c in data.get("exam_changes", [])]])
        if not drug_bearing(text):
            return data
        if self.llm is None:
            raise LayerRejected(["event names a drug and no safety judge is reachable"])
        msgs = [{"role": "system", "content": "ROLE: judge:safety_event\nYou check one bedside event of a "
                 "synthetic training case for unsafe drug or dose statements. Answer pass unless a drug or "
                 "dose is clinically wrong for the event."},
                {"role": "user", "content": f"CONDITION: {state['condition']['label_en']}\nEVENT: {text}"}]
        reply = await self.llm.complete_json(msgs, schema=SAFETY_EVENT_SCHEMA, schema_name="safety_event",
                                             role="judge", temperature=0.0, max_tokens=150, node="safety_event")
        ok = str(reply.data.get("verdict") or "pass") == "pass"
        self.emit(thread_id, "judge", {"layer": layer, "judge": "safety_event", "blocking": True,
                                       "decision": "accept" if ok else "rejected",
                                       "issues": list(reply.data.get("issues") or [])})
        if not ok:
            raise SafetyVeto(list(reply.data.get("issues") or ["unsafe drug statement in event"]))
        return data

    # ---------------------------------------------------------- async judges -> patches
    async def _judge_async(self, thread_id: str) -> None:
        state = self.store.get(thread_id)
        if state is None or state.get("status") == "failed" or self.llm is None:
            return
        spec = source_spec(state) if state.get("opening") else {}
        votes = await asyncio.gather(*(J.run_judge(n, spec, state["condition"], self.llm, round_no=0)
                                       for n in ("clinical_consistency", "pedagogy")), return_exceptions=True)
        issues: list[str] = [f"[course] {i}" for i in J.check_course_rules(spec, state["condition"])["issues"]]
        for res in votes:
            if isinstance(res, BaseException):
                continue
            vote, event = res
            self.store.update(thread_id, lambda s, e=event: s.update(trace=(list(s.get("trace") or []) + [e])[-80:]))
            issues += [f"[{vote['judge']}] {i}" for i in vote.get("issues") or [] if not _single_shot_rule(i)]
        council = {"decision": "accept" if not issues else "patched", "issues": issues, "async": True}
        self.store.update(thread_id, lambda s: s.update(council=council))
        if not issues:
            self.emit(thread_id, "judge", {"layer": "*", "decision": "accept"})
            return
        # Each patch rewrites a different layer from the same review, so they run together
        # (live 2026-10-21: three patches one after another added about 20 s before ``done``).
        await asyncio.gather(*(self._patch(thread_id, layer, layer_issues)
                               for layer, layer_issues in self._issues_by_layer(state, issues).items()),
                             return_exceptions=True)

    async def _patch(self, thread_id: str, layer: str, layer_issues: list[str]) -> None:
        """Rewrite one unseen layer with the judges' issues, or record them on a seen one."""
        entry = (self.store.get(thread_id) or {}).get("layers", {}).get(layer) or {}
        if layer == "opening" or entry.get("seen"):
            note = {"layer": layer, "issues": layer_issues, "action": "noted"}
            self.store.update(thread_id, lambda s: s.update(corrections=list(s.get("corrections") or []) + [note]))
            self.emit(thread_id, "judge", {"layer": layer, "decision": "noted", "issues": layer_issues})
            return
        before = entry.get("data")
        await self._generate_layer(thread_id, layer, issues=layer_issues)
        after = ((self.store.get(thread_id) or {}).get("layers", {}).get(layer) or {}).get("data")
        if after is not None and after != before:
            st = self.store.get(thread_id) or {}
            self.emit(thread_id, "judge", {"layer": layer, "decision": "patched", "issues": layer_issues,
                                           "patch": [{"op": "replace", "path": f"/layers/{layer}", "value": after}],
                                           "spec": st.get("spec")})
        else:
            self.emit(thread_id, "judge", {"layer": layer, "decision": "noted", "issues": layer_issues})

    @staticmethod
    def _issues_by_layer(state: dict[str, Any], issues: list[str]) -> dict[str, list[str]]:
        ready = [n for n, e in (state.get("layers") or {}).items() if e.get("status") == "ready"]
        out: dict[str, list[str]] = {}
        for issue in issues:
            low = issue.lower()
            if "rule:allergy_structured" in low:
                target = "history.background" if "history.background" in ready else None
            elif "rule:effect_sign" in low or "rule:definitive_covers_deadline" in low:
                target = "treatments" if "treatments" in ready else None
            elif "rule:untreated_worsens" in low or "rule:complication_plan_present" in low:
                target = "opening"      # kernel and course class: recorded, the shown opening is kept
            elif "hpi" in low or "history" in low or "red flag" in low or "complaint" in low:
                target = next((n for n in ready if n.startswith("history.")), None)
                if "chief complaint" in low:
                    target = "opening"
            elif "exam" in low:
                target = next((n for n in ready if n.startswith("exam.")), None)
            elif "lab" in low or "imaging" in low:
                target = "results" if "results" in ready else None
            elif "triage" in low or "vital" in low or "acuity" in low:
                target = "opening"
            else:
                target = None
            if target:
                out.setdefault(target, []).append(issue)
        return out


def _single_shot_rule(issue: str) -> bool:
    """Deterministic rules written for one whole-case author call that do not apply to a layered
    case: the history is answered per question cluster, so the 4-10 core HPI bound of a
    single draft is not a defect here."""
    return "core items" in issue and "hpi has" in issue


