class LayerRejected(ValueError):
    """A layer failed its deterministic gate; the issues are given back to the next attempt."""

    def __init__(self, issues: list[str]) -> None:
        super().__init__("; ".join(issues))
        self.issues = issues


class SafetyVeto(LayerRejected):
    """The safety gate (deterministic treatment checks, the blocking safety judge, or the event
    safety judge) rejected a drug-bearing layer. After the allowed rewrite the layer fails with
    ``error: "safety_veto"`` and its reason; nothing is substituted for it (06b F30)."""


def _num(v: Any, default: float) -> float:
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def gate_s1(draft: dict[str, Any], cond: dict[str, Any], *, acuity: int,
            complaint: Optional[str] = None) -> tuple[dict[str, Any], list[str]]:
    """Deterministic S1 (opening) checks. Returns (draft, notes); raises LayerRejected when unusable."""
    notes: list[str] = []
    issues: list[str] = []
    opening = draft.get("opening") if isinstance(draft.get("opening"), dict) else None
    if opening is None:
        raise LayerRejected(["the opening is required"])
    demo = opening.setdefault("demographics", {})
    lo, hi = cond.get("age") or (1, 105)
    age = int(_num(demo.get("age"), (lo + hi) / 2))
    if not (lo <= age <= hi):
        notes.append(f"age {age} outside {lo}-{hi} for {cond['id']}: clamped")
        age = max(lo, min(hi, age))
    demo["age"] = age
    want_sex = cond.get("sex")
    sex = str(demo.get("sex") or "").lower()
    if want_sex in ("male", "female") and sex != want_sex:
        notes.append(f"sex {sex!r} implausible for {cond['id']}: set to {want_sex}")
        sex = want_sex
    demo["sex"] = sex if sex in ("male", "female") else "female"
    if not str(demo.get("name") or "").strip():
        issues.append("demographics.name is empty")
    if not str(opening.get("chief_complaint") or "").strip():
        issues.append("chief_complaint is empty")
    tv = opening.get("triage_vitals") or {}
    for key in VITAL_KEYS:
        if key not in tv:
            issues.append(f"triage_vitals.{key} missing")
            continue
        lo_b, hi_b = J.VITAL_BOUNDS[key]
        val = _num(tv[key], lo_b)
        if not (lo_b <= val <= hi_b):
            notes.append(f"triage {key}={val} clamped to {lo_b}-{hi_b}")
            val = max(lo_b, min(hi_b, val))
        tv[key] = round(val, 1) if key == "tempC" else int(round(val))
    if all(k in tv for k in ("systolic", "diastolic")) and tv["diastolic"] >= tv["systolic"]:
        tv["diastolic"] = max(int(J.VITAL_BOUNDS["diastolic"][0]), int(tv["systolic"]) - 30)
        notes.append("triage diastolic lowered below systolic")
    env = J._ESI_ENVELOPE.get(acuity) if age >= 16 else None  # adult envelope only
    for key, (elo, ehi) in (env or {}).items():
        if key in tv and not (elo <= float(tv[key]) <= ehi):
            notes.append(f"triage {key}={tv[key]} outside the ESI {acuity} envelope {elo}-{ehi}")
    statements = [s for s in opening.get("opening_statements") or [] if str((s or {}).get("text") or "").strip()]
    if not statements:
        issues.append("opening_statements is empty")
    opening["opening_statements"] = statements
    visible = " ".join([str(opening.get("chief_complaint") or ""), str(opening.get("triage_note") or ""),
                        *[str(s.get("text") or "") for s in statements]])
    if _DOSE_RE.search(visible):
        issues.append("the opening states a drug dose; the opening carries no drug content")
    if complaint:
        probs = J.complaint_problems({"chief_complaint_en": opening.get("chief_complaint"),
                                      "hpi": [{"answer_en": s.get("text")} for s in statements]}, complaint)
        if probs and not J.complaint_problems({"chief_complaint_en": visible}, complaint):
            probs = []
        issues.extend(probs[:1])
    if issues:
        raise LayerRejected(issues)
    return {"opening": opening}, notes


def gate_kernel(kernel: dict[str, Any], cond: Optional[dict[str, Any]] = None) -> tuple[dict[str, Any], list[str]]:
    """Deterministic kernel checks (consistency with the condition is the async judges' job).
    Branch ids are validated against the condition's course library (06b 4.5: anything
    unknown is dropped, not executed); flags and allergies against closed vocabularies."""
    notes: list[str] = []
    lib = course_library(cond["id"]) if cond else {"branches": []}
    if lib["branches"]:
        known = set(lib["branches"])
        kept = [b for b in kernel.get("branches") or [] if isinstance(b, dict) and b.get("id") in known]
        dropped = [str((b or {}).get("id")) for b in kernel.get("branches") or [] if b not in kept]
        if dropped:
            notes.append(f"kernel branches {dropped} are not in the course library: dropped")
        kernel["branches"] = kept
    kernel["flags"] = [f for f in kernel.get("flags") or [] if f in COURSE_FLAGS][:3]
    kernel["allergies"] = [a for a in kernel.get("allergies") or [] if isinstance(a, dict)
                           and a.get("agent_class") in ALLERGY_CLASSES and a.get("reaction") in ALLERGY_REACTIONS][:2]
    if len([p for p in kernel.get("key_positives") or [] if str(p).strip()]) < 2:
        raise LayerRejected(["key_positives needs at least two findings"])
    if kernel.get("course") not in COURSES:
        kernel["course"] = "stable"
        notes.append("kernel.course defaulted to stable")
    kernel["exam_systems"] = [s for s in kernel.get("exam_systems") or [] if s in EXAM_SYSTEMS and s != "general"][:2]
    kernel["branches"] = [b for b in kernel.get("branches") or []
                          if isinstance(b, dict) and re.fullmatch(r"[a-z0-9_]{2,40}", str(b.get("id") or ""))][:3]
    return kernel, notes


def gate_layer(layer: str, data: dict[str, Any], state: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Deterministic per-layer checks; coerce what is safe to coerce, reject the rest."""
    kind, _, sub = layer.partition(".")
    notes: list[str] = []
    cond = state["condition"]
    if kind == "history":
        allowed = HISTORY_CLUSTERS[sub]
        items = []
        for it in data.get("items") or []:
            if not isinstance(it, dict) or not str(it.get("text") or "").strip():
                continue
            intent = str(it.get("intent") or "")
            if intent not in allowed:
                notes.append(f"intent {intent!r} outside {sub}: set to {allowed[0]}")
                intent = allowed[0]
            items.append({"intent": intent, "text": str(it["text"]).strip(), "red_flag": bool(it.get("red_flag")),
                          "topic": str(it.get("topic") or "")[:24]})
        if not items:
            raise LayerRejected([f"history.{sub} has no usable item"])
        data = {**data, "items": items}
        if sub == "background":
            problems = []
            if not str(data.get("pmh") or "").strip():
                problems.append("pmh is empty: write the past medical history (or 'No significant history')")
            allergy_text = str(data.get("allergies") or "")
            if not allergy_text.strip():
                problems.append("allergies is empty: state the allergies or 'No known drug allergies'")
            for a in (state.get("kernel") or {}).get("allergies") or []:
                if a.get("agent_class") and not names_allergy(allergy_text, a["agent_class"]):
                    problems.append(f"allergies must state the {a['agent_class']} allergy ({a.get('reaction')})")
            if problems:
                raise LayerRejected(problems)
    elif kind == "exam":
        allowed = EXAM_SYSTEMS[sub]
        items = []
        for it in data.get("items") or []:
            if not isinstance(it, dict) or not str(it.get("finding") or "").strip():
                continue
            man = str(it.get("maneuver") or "")
            if man not in allowed:
                man = allowed[0]
            items.append({"maneuver": man, "system": str(it.get("system") or sub), "finding": str(it["finding"]),
                          "abnormal": bool(it.get("abnormal"))})
        if not items:
            raise LayerRejected([f"exam.{sub} has no usable finding"])
        data = {"items": items}
    elif kind == "treatments":
        vocab = N.condition_treatments(cond)
        rows: list[dict[str, Any]] = []
        seen: set[str] = set()
        for t in data.get("treatments") or []:
            if not isinstance(t, dict):
                continue
            row = {"code": str(t.get("code") or "").strip(), "label_en": str(t.get("label") or ""),
                   "appropriateness": str(t.get("appropriateness") or "neutral"),
                   "effects": [dict(e) for e in t.get("effects") or [] if isinstance(e, dict)],
                   "narrative": str(t.get("narrative") or "")}
            code = N.resolve_treatment_code(row, vocab)
            if code is None:
                notes.append(f"dropped uncoded treatment {row['label_en']!r}")
                continue
            if code in seen:
                continue
            seen.add(code)
            row["code"] = code
            notes.extend(N.clamp_effects(row))
            for eff in row["effects"]:
                cap = J.EFFECT_CAPS.get(str(eff.get("key") or ""))
                d = _num(eff.get("delta"), 0.0)
                if cap is not None and abs(d) > cap:
                    eff["delta"] = cap if d > 0 else -cap
                    notes.append(f"{code}: effect {eff.get('key')} clamped to {eff['delta']}")
            rows.append(row)
        draft = {"treatments": rows}
        det = J.check_safety_dosing(draft, cond)
        hard = [i for i in det["issues"] if "no indicated" in i or "marked indicated" in i
                or "marked contraindicated" in i or "no treatments" in i]
        if hard:
            raise SafetyVeto(hard)
        notes.extend(i for i in det["issues"] if i not in hard)
        disp = str(data.get("disposition") or "")
        data = {"treatments": rows, "disposition": disp if disp in DISPOSITIONS else (cond.get("disposition")
                                                                                      or "observation")}
    elif kind == "results":
        demo = (state.get("opening") or {}).get("demographics") or {}
        labs = []
        for lab in data.get("labs") or []:
            if not isinstance(lab, dict) or not str(lab.get("label") or "").strip():
                continue
            labs.append({"code": str(lab.get("code") or ""), "label_en": str(lab["label"]),
                         "value": lab.get("value"), "unit": str(lab.get("unit") or ""),
                         "ref_low": lab.get("ref_low"), "ref_high": lab.get("ref_high"),
                         "flag": str(lab.get("flag") or "N").upper()})
        notes.extend(N.normalize_labs(labs, str(demo.get("sex") or "female"), int(_num(demo.get("age"), 45))))
        for lab in labs:
            lo, hi, val = lab.get("ref_low"), lab.get("ref_high"), lab.get("value")
            try:
                fv = float(val)
                if lo is not None and fv < float(lo) and lab["flag"] not in ("L", "LL"):
                    lab["flag"] = "L"
                    notes.append(f"lab {lab['code']}: flag set to L from the reference interval")
                elif hi is not None and fv > float(hi) and lab["flag"] not in ("H", "HH"):
                    lab["flag"] = "H"
                    notes.append(f"lab {lab['code']}: flag set to H from the reference interval")
                elif lo is not None and hi is not None and float(lo) <= fv <= float(hi) and lab["flag"] != "N":
                    lab["flag"] = "N"
                    notes.append(f"lab {lab['code']}: flag set to N from the reference interval")
            except (TypeError, ValueError):
                continue
        imaging = [{"code": str(im.get("code") or ""), "modality_en": str(im.get("modality") or ""),
                    "findings_en": str(im.get("findings") or ""), "image_query_en": str(im.get("image_query") or "")}
                   for im in data.get("imaging") or [] if isinstance(im, dict) and str(im.get("findings") or "").strip()]
        if not labs and not imaging:
            raise LayerRejected(["results has neither labs nor imaging"])
        data = {"labs": labs, "imaging": imaging}
    elif kind == "event":
        facts = [str(f).strip() for f in data.get("facts") or [] if str(f).strip()]
        if not facts and not str(data.get("nurse_call") or "").strip():
            raise LayerRejected([f"event {sub} has no new fact"])
        data = {"facts": facts, "nurse_call": str(data.get("nurse_call") or ""),
                "exam_changes": [c for c in data.get("exam_changes") or []
                                 if isinstance(c, dict) and c.get("maneuver") in MANEUVERS and c.get("finding")],
                "affect": str(data.get("affect") or "")}
    else:
        points = [str(p).strip() for p in data.get("teaching_points") or [] if str(p).strip()]
        if not points:
            raise LayerRejected(["debrief has no teaching point"])
        anchors, _ = resolve_anchors(list((state.get("kernel") or {}).get("anchor_ids") or []), cond)
        data = {"teaching_points": points, "missed_cues": [str(c) for c in data.get("missed_cues") or []],
                "anchors": [{"statement_id": a["statement_id"], "statement_en": a["statement_en"],
                             "statement_tr": a.get("statement_tr") or "", "title": a.get("title") or "",
                             "source": a["source"], "citation": a["citation"]} for a in anchors]}
    return data, notes


def failure_reason(layer: str, code: str, attempts: int) -> str:
    """One plain sentence for a failed layer (shown with Retry; never a substitute layer)."""
    kind = layer_kind(layer)
    what = {"treatments": "the treatment table", "event": "the bedside event", "results": "the results",
            "debrief": "the debrief", "history": "this part of the history",
            "exam": "these examination findings"}.get(kind, "this part of the case")
    if code == "safety_veto":
        tries = "the rewrite" if attempts > 1 else "the first draft"
        return f"The safety review rejected {what} after {tries}; it is not shown until a safe version is written."
    if code == "model_unreachable":
        return f"The model could not be reached, so {what} was not written."
    return f"The model did not write a usable version of {what}."


def debrief_extra(diagnosis: Optional[dict[str, Any]]) -> str:
    """The committed diagnosis as one short prompt line (picklist code and display, no free text)."""
    if not isinstance(diagnosis, dict):
        return ""
    code = re.sub(r"[^A-Za-z0-9.\-]", "", str(diagnosis.get("code") or ""))[:16]
    display = re.sub(r"\s+", " ", str(diagnosis.get("display") or "")).strip()[:80]
    if not code and not display:
        return ""
    return f"The learner committed the diagnosis {display or code} ({code or 'no code'}): say whether it fits."


_DRUG_WORDS: Optional[re.Pattern[str]] = None


def drug_bearing(text: str) -> bool:
    """True when a text names a catalogue drug or states a dose (safety judge required)."""
    global _DRUG_WORDS
    if _DRUG_WORDS is None:
        words = sorted({w.lower() for _c, en, _tr, _cls in N.WEB_TREATMENT_CATALOG
                        for w in re.findall(r"[A-Za-z]{5,}", en)} - {"fluid", "fluids", "oxygen", "bolus",
                                                                      "therapy", "support", "position"})
        _DRUG_WORDS = re.compile(r"\b(?:" + "|".join(map(re.escape, words)) + r")\b", re.I) if words else re.compile(r"$^")
    return bool(_DOSE_RE.search(text or "") or _DRUG_WORDS.search(text or ""))


