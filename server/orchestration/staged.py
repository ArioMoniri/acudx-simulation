# Fields of the Director state that come from case content; refreshed when a layer lands so
# a Director state created from the opening learns the new history, exam and treatment rows.
DIRECTOR_CONTENT_KEYS = ("treatments", "facts_by_trigger", "baseline", "condition_label_en", "condition_label_tr")


def director_state_from_spec(spec: dict[str, Any], thread_id: str) -> dict[str, Any]:
    from server.orchestration.director import CaseState

    return CaseState.from_spec(spec, case_id=thread_id).model_dump()


def refresh_director(state: dict[str, Any]) -> None:
    """Fold newly authored content into an existing Director state, keeping its dynamics."""
    current = state.get("director")
    if not isinstance(current, dict) or not state.get("spec"):
        return
    try:
        fresh = director_state_from_spec(state["spec"], state["thread_id"])
    except Exception:  # noqa: BLE001 - the Director model may change shape; never break a layer
        return
    for key, value in fresh.items():
        if key not in current or key in DIRECTOR_CONTENT_KEYS:
            current[key] = value
    if not current.get("pending_complications") and fresh.get("pending_complications"):
        current["pending_complications"] = fresh["pending_complications"]


def layers_for_action(kind: str, ref: str) -> list[str]:
    """Which layers a learner action reads (marks them seen; lazily generates them)."""
    if kind == "question":
        c = intent_cluster(ref)
        return [f"history.{c}"] if c else []
    if kind == "exam":
        s = maneuver_system(ref)
        return [f"exam.{s}"] if s else []
    if kind == "order":
        return ["results"]
    if kind == "treatment":
        return ["treatments"]
    return []


