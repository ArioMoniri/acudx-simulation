def _bi(text: Any) -> tuple[str, str]:
    """Single-locale generation: the generated text fills both locale slots; ``meta.locale``
    says which language it is (TR is generated on request when the UI language is TR)."""
    s = str(text or "")
    return s, s


def derived_trajectory(triage: dict[str, Any], course: str) -> list[dict[str, Any]]:
    """Untreated baseline course from the model's triage vitals and course class. The Director
    applies treatment effects and branches on top; this is physiology, not authored content."""
    step = {"deteriorating": {"hr": 5, "systolic": -5, "diastolic": -3, "rr": 2, "spo2": -1, "tempC": 0.1},
            "improving": {"hr": -3, "systolic": 2, "diastolic": 1, "rr": -1, "spo2": 1, "tempC": -0.1},
            "stable": {}}.get(course, {})
    out = []
    for i, at in enumerate((0, 900_000, 1_800_000, 3_600_000)):
        pt: dict[str, Any] = {"atMs": at}
        for k in VITAL_KEYS:
            lo, hi = J.VITAL_BOUNDS[k]
            v = _num(triage.get(k), (lo + hi) / 2) + step.get(k, 0) * i
            v = max(lo, min(hi, v))
            pt[k] = round(v, 1) if k == "tempC" else int(round(v))
        if pt["diastolic"] >= pt["systolic"]:
            pt["diastolic"] = pt["systolic"] - 20
        out.append(pt)
    return out


def assemble_spec(state: dict[str, Any]) -> dict[str, Any]:
    cond = state["condition"]
    opening = state.get("opening") or {}
    kernel = state.get("kernel") or {}
    layers = state.get("layers") or {}
    order = list(state.get("layer_order") or [])
    demo = opening.get("demographics") or {}
    cc_en, cc_tr = _bi(opening.get("chief_complaint"))
    hpi: list[dict[str, Any]] = []
    for i, s in enumerate(opening.get("opening_statements") or []):
        a, b = _bi(s.get("text"))
        hpi.append({"uid": f"op.{i}", "layer": "opening", "intent": s.get("intent") or "onset",
                    "answer_en": a, "answer_tr": b, "red_flag": False, "topic": ""})
    exam: list[dict[str, Any]] = []
    labs: list[dict[str, Any]] = []
    imaging: list[dict[str, Any]] = []
    treatments: list[dict[str, Any]] = []
    pmh = meds = allergies = ""
    disposition = cond.get("disposition") or "observation"
    events: list[dict[str, Any]] = []
    for name in order:
        entry = layers.get(name) or {}
        if entry.get("status") != "ready":
            continue
        data = entry.get("data") or {}
        kind, _, sub = name.partition(".")
        if kind == "history":
            for i, it in enumerate(data.get("items") or []):
                a, b = _bi(it.get("text"))
                hpi.append({"uid": f"{name}.{i}", "layer": name, "intent": it["intent"], "answer_en": a,
                            "answer_tr": b, "red_flag": bool(it.get("red_flag")), "topic": it.get("topic") or ""})
            if sub == "background":
                pmh, meds, allergies = (str(data.get("pmh") or ""), str(data.get("meds") or ""),
                                        str(data.get("allergies") or ""))
        elif kind == "exam":
            for i, it in enumerate(data.get("items") or []):
                sa, sb = _bi(it.get("system"))
                fa, fb = _bi(it.get("finding"))
                exam.append({"uid": f"{name}.{i}", "layer": name, "maneuver": it["maneuver"], "system_en": sa,
                             "system_tr": sb, "finding_en": fa, "finding_tr": fb, "abnormal": bool(it.get("abnormal"))})
        elif kind == "treatments":
            for t in data.get("treatments") or []:
                la, lb = _bi(t.get("label_en"))
                na, nb = _bi(t.get("narrative"))
                treatments.append({"code": t["code"], "label_en": la, "label_tr": lb,
                                   "appropriateness": t["appropriateness"], "effects": t.get("effects") or [],
                                   "narrative_en": na, "narrative_tr": nb})
            disposition = data.get("disposition") or disposition
        elif kind == "results":
            for i, lab in enumerate(data.get("labs") or []):
                la, lb = _bi(lab.get("label_en"))
                labs.append({**lab, "uid": f"results.lab.{i}", "label_en": la, "label_tr": lb,
                             "category": "chemistry"})
            for i, im in enumerate(data.get("imaging") or []):
                ma, mb = _bi(im.get("modality_en"))
                fa, fb = _bi(im.get("findings_en"))
                qa, qb = _bi(im.get("image_query_en"))
                imaging.append({"uid": f"results.img.{i}", "code": im.get("code") or "", "modality_en": ma,
                                "modality_tr": mb, "findings_en": fa, "findings_tr": fb,
                                "image_query_en": qa, "image_query_tr": qb})
        elif kind == "event":
            for i, ch in enumerate(data.get("exam_changes") or []):
                fa, fb = _bi(ch.get("finding"))
                exam.append({"uid": f"{name}.{i}", "layer": name, "maneuver": ch["maneuver"],
                             "system_en": ch["maneuver"], "system_tr": ch["maneuver"],
                             "finding_en": fa, "finding_tr": fb, "abnormal": True})
            events.append({"id": sub, "layer": name, "at_ms": entry.get("at_ms"), "facts": data.get("facts") or [],
                           "nurse_call": data.get("nurse_call") or "", "affect": data.get("affect") or ""})
    pa, pb = _bi(pmh)
    ma, mb = _bi(meds)
    aa, ab = _bi(allergies)
    triage = dict(opening.get("triage_vitals") or {})
    spec: dict[str, Any] = {
        "seed": state["seed"], "locale": state["locale"],
        "condition": {"icd11": cond.get("icd11", ""), "icd10": cond.get("icd10", ""), "dsm5tr": cond.get("dsm5tr"),
                      "label_en": cond["label_en"], "label_tr": cond["label_tr"], "system": cond["system"]},
        "demographics": {"age": demo.get("age"), "sex": demo.get("sex"), "name_hint": demo.get("name") or ""},
        "chief_complaint_en": cc_en, "chief_complaint_tr": cc_tr,
        "acuity_esi": state["acuity"], "difficulty": state["difficulty"],
        "hpi": hpi, "pmh_en": pa, "pmh_tr": pb, "meds_en": ma, "meds_tr": mb, "allergies_en": aa, "allergies_tr": ab,
        "exam": exam, "triage_vitals": triage,
        "vitals_trajectory": derived_trajectory(triage, str(kernel.get("course") or "stable")) if triage else [],
        "labs": labs, "imaging": imaging, "treatments": treatments, "disposition": disposition,
        "guideline_anchors": list(state.get("anchors") or []),
        "red_flags": [{"en": _bi(r.get("text"))[0], "tr": _bi(r.get("text"))[1], "channel": r.get("channel") or "clinician"}
                      for r in kernel.get("red_flags") or []],
        "triage_note": str(opening.get("triage_note") or ""),
        "persona": dict(opening.get("persona") or {}),
        "events": events,
    }
    spec["meta"] = {
        "source": "model", "generator": "v2", "pipeline": "staged", "thread_id": state["thread_id"],
        "condition_id": cond["id"], "locale": state["locale"],
        "model": state.get("model"), "models": sorted(set(state.get("models") or [])),
        "layers": {n: (layers.get(n) or {}).get("status") for n in order},
        "council": state.get("council"), "corrections": list(state.get("corrections") or []),
        "gap_filled": [], "normalization": list(state.get("normalization") or [])[-60:],
        "degraded": bool(state.get("degraded")), "note": state.get("degraded_note"),
        "latency_ms": (state.get("timings") or {}).get("t_opening_ms"),
        "timings": dict(state.get("timings") or {}),
    }
    return spec


