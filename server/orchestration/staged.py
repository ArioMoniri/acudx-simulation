"""Staged, on-request case generation (review 06a, section 4).

One learner request creates one thread (``thread_id``) and one hidden case kernel.
Everything the learner sees is a *layer* written by a short model call from the kernel,
in the requested locale only, and stored server-side in :class:`CaseStore`.

    S0  sample          condition from the taxonomy (+ learner steering, faculty blueprint)
    S1  opening         ONE streamed call (cap S1_MAX_TOKENS): demographics, complaint, triage
                        note and vitals, persona, two opening statements. Deterministic gate
                        only (bounds, plausibility, no drug content), so the encounter opens on
                        ``opening.ready`` without any judge.
        kernel          ONE short call right after the opening, conditioned on it (cap
                        MAX_TOKENS["kernel"]): key positives and negatives, course, branches,
                        red flags, exam systems, anchor ids. Hidden; it seeds every layer.
                        (Live 2026-10-20 on one A100 in eager mode: one combined call of about
                        560 tokens took 40 to 48 s, so the kernel moved off the critical path.)
    S2  history.<cluster>   presenting | associated | background
    S3  exam.<system>       general | cardiovascular | respiratory | abdominal | neurological |
                            msk_skin | ent_special
    S4  treatments          blocking safety gate (deterministic + safety judge)
    S5  results             labs and imaging prose (numbers move with the engine later)
    S6  event.<id>          a Director branch event; safety-gated when it names a drug
    S7  debrief             teaching points + verified guideline anchors

Layers are generated by same-thread background continuation right after the opening
(allowed by the owner: the case was asked for) or lazily on first access. Nothing is
generated before a learner asks, nothing is pooled, nothing is reused across threads,
and no template, seed or fixture is ever served as a layer: when a layer fails it is
regenerated or reported as failed with Retry; fixtures are used only as a validation
oracle (treatment appropriateness).

Model judges are asynchronous: after the core layers land, the clinical-consistency
and pedagogy judges review the assembled case and may PATCH one unseen layer (a field
level JSON Patch on ``/layers/<name>``); a layer the learner has already seen is never
rewritten under them, the issue is recorded as a correction note instead.

SSE event log (``CaseStore.append_event``; contract in review 06a 4.6)::

    start          {thread_id, stages, eta_ms}
    opening.delta  {path, value}
    opening.ready  {opening, spec, layers, timings}
    kernel         {status:"ready"} (or error stage "kernel", non-fatal)
    layer.pending  {layer, reason}
    layer.ready    {layer, data, spec}
    judge          {layer, decision: accept|patched|noted, patch?, issues?}
    error          {stage, error, status, retryable, thread_id}
    done           {thread_id, spec, timings}

Education only. Synthetic patients.
"""

