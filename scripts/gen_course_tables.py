"""Generate the browser mirror of the course tables and the shared parity fixture.

    .venv/bin/python scripts/gen_course_tables.py          # write both files
    .venv/bin/python scripts/gen_course_tables.py --check  # exit 1 if either is stale

* ``web/src/domain/courseTables.generated.ts``: every course rule expanded with
  its pattern, the class effect curves, lab rates, catalogue classes, spectrum
  and allergen tables, row classes for every fixture row and the ICD-10 index,
  exported as one JSON object. ``server/tests/test_course_parity.py`` fails when
  this file differs from what the server tables produce (review 06b F26:
  one table, generated into both languages).
* ``server/tests/fixtures/course_parity.json``: the reviewers' simulation
  scenarios (``server/tests/director_sim.SCENARIOS``) as engine inputs with the
  Director's vitals at t10, t30, t60 and t120; the Vitest suite replays them
  through ``clinicalCourse.ts`` (06b acceptance test 10).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from server import case_fixtures as FX  # noqa: E402
from server.condition_catalog import CATALOG  # noqa: E402
from server.orchestration import course as C  # noqa: E402
from server.orchestration.normalize import classify_treatment  # noqa: E402

TS_PATH = ROOT / "web/src/domain/courseTables.generated.ts"
FIXTURE_PATH = ROOT / "server/tests/fixtures/course_parity.json"
PARITY_MARKS = (10, 30, 60, 120)


def tables() -> dict:
    rules = {cid: C.expand_rule(cid) for cid in sorted(FX.CONDITION_COURSE)}
    row_classes: dict[str, list[str]] = {}
    for fx in FX.CONDITION_FIXTURES.values():
        for t in fx.get("treatments", []):
            row_classes.setdefault(t[0], classify_treatment(f"{t[1]} {t[0]}"))
    return {
        "rules": rules,
        "stable": C.fallback_rule("stable"),
        "classEffects": FX.CLASS_EFFECTS,
        "labRates": FX.LAB_RATES,
        "codeClasses": FX.CODE_CLASSES,
        "agentCoverage": FX.AGENT_COVERAGE,
        "agentAllergyClass": FX.AGENT_ALLERGY_CLASS,
        "rowClasses": dict(sorted(row_classes.items())),
        "handledClasses": sorted(C.HANDLED_CLASSES),
        "bounds": {k: list(v) for k, v in C.BOUNDS.items()},
        "defaultBedside": C.DEFAULT_BEDSIDE,
        "icd10": {c["id"]: c["icd10"] for c in CATALOG if c["id"] in FX.CONDITION_COURSE},
        "sources": FX.COURSE_SOURCES,
    }


def ts_source() -> str:
    body = json.dumps(tables(), ensure_ascii=False, indent=1, sort_keys=True)
    return (
        "/**\n"
        " * GENERATED by scripts/gen_course_tables.py from server/case_fixtures.py and\n"
        " * server/orchestration/course.py. Do not edit by hand: change the server\n"
        " * tables and regenerate. server/tests/test_course_parity.py diffs this file\n"
        " * against the server (review 06b F26, one physiology table for both sides).\n"
        " */\n\n"
        "import type { CourseTables } from \"@/domain/clinicalCourse\";\n\n"
        f"export const COURSE_TABLES: CourseTables = {body};\n"
    )


def parity_fixture() -> dict:
    from server.tests.director_sim import SCENARIOS, run
    cases = []
    for cid, plans in SCENARIOS.items():
        for label, plan in plans:
            r = run(cid, plan, label=label, until=max(PARITY_MARKS))
            course = r.state.course
            cases.append({
                "condition_id": cid, "label": label,
                "input": {"condition_id": course["condition_id"], "t0": course["t0"], "seed": course["seed"],
                          "patient": course["patient"], "events": r.state.events},
                "expect": {str(m): {"vitals": r.minutes[m]["vitals"], "phase": r.minutes[m]["phase"],
                                    "gcs": r.minutes[m]["bedside"]["gcs"], "lactate": r.minutes[m]["bedside"]["lactate"],
                                    "active_diagnoses": r.minutes[m]["active_diagnoses"]} for m in PARITY_MARKS},
            })
    return {"marks": list(PARITY_MARKS), "cases": cases}


def main(argv: list[str]) -> int:
    ts = ts_source()
    fixture = json.dumps(parity_fixture(), ensure_ascii=False, indent=1, sort_keys=True) + "\n"
    if "--check" in argv:
        stale = [str(p) for p, text in ((TS_PATH, ts), (FIXTURE_PATH, fixture))
                 if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print("stale: " + ", ".join(stale))
            return 1
        return 0
    TS_PATH.write_text(ts, encoding="utf-8")
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(fixture, encoding="utf-8")
    print(f"wrote {TS_PATH.relative_to(ROOT)} and {FIXTURE_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
